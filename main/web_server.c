/*
 * web_server.c - TF card file browser: list, download and preview.
 *
 * Endpoints
 *   GET /                         embedded single-page UI
 *   GET /files                    JSON: { mount, logging, files:[{name,size}] }
 *   GET /download?f=NAME          raw file as an attachment
 *   GET /preview?f=NAME&tail=0|1  first / last APP_WEB_PREVIEW_LINES lines
 *
 * Concurrency
 * -----------
 * The logger task and this server both touch the card. Every FATFS call is
 * wrapped in the shared recursive lock from logger_sd.h, but the lock is
 * released around socket writes: a slow client must never stall the 100 Hz
 * acquisition pipeline. Download therefore reads one chunk under the lock and
 * then sends it unlocked.
 */
#include "web_server.h"

#include <dirent.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>

#include "app_config.h"
#include "logger_sd.h"

#include "esp_http_server.h"
#include "esp_log.h"

static const char *TAG = "web";

/*
 * Embedded by EMBED_FILES in main/CMakeLists.txt. Note that ESP-IDF derives the
 * symbol from the file's *basename* only, so "web/index.html" becomes
 * _binary_index_html_start/_end.
 */
extern const uint8_t index_html_start[] asm("_binary_index_html_start");
extern const uint8_t index_html_end[]   asm("_binary_index_html_end");

#define SD_LOCK_TIMEOUT_MS   1000
#define DOWNLOAD_CHUNK_BYTES 2048
#define PREVIEW_MAX_BYTES    (64 * 1024)
#define MAX_NAME_LEN         64

/* ------------------------------------------------------------------ helpers */

/* snprintf() returns the length it *would* have written; keep it in bounds. */
static int clamp_len(int n, size_t bufsz)
{
    if (n < 0) {
        return 0;
    }
    if ((size_t)n >= bufsz) {
        return (int)bufsz - 1;
    }
    return n;
}

/*
 * Reject anything that could escape the mount point, and anything that would
 * need escaping in the JSON reply (all names here are generated by the
 * firmware, so this is belt and braces).
 */
static bool name_is_safe(const char *name)
{
    if (!name || !*name || strlen(name) > MAX_NAME_LEN) {
        return false;
    }
    if (strstr(name, "..") != NULL) {
        return false;
    }
    if (strchr(name, '/') || strchr(name, '\\')) {
        return false;
    }
    if (strchr(name, '"') || strchr(name, '\n') || strchr(name, '\r')) {
        return false;
    }
    return true;
}

/* Resolve a request-supplied name to an existing regular file. */
static bool resolve_file(const char *name, char *path, size_t path_len)
{
    if (!name_is_safe(name)) {
        return false;
    }

    const int n = snprintf(path, path_len, "%s/%s", APP_LOG_MOUNT_POINT, name);
    if (n < 0 || (size_t)n >= path_len) {
        return false;
    }

    struct stat st;
    return stat(path, &st) == 0 && S_ISREG(st.st_mode);
}

static bool get_name_arg(httpd_req_t *req, char *out, size_t out_len)
{
    char query[160];

    if (httpd_req_get_url_query_len(req) <= 0) {
        return false;
    }
    if (httpd_req_get_url_query_str(req, query, sizeof(query)) != ESP_OK) {
        return false;
    }
    return httpd_query_key_value(query, "f", out, out_len) == ESP_OK;
}

/* Byte length of the first `lines` lines of buf. */
static size_t first_lines_len(const char *buf, size_t len, unsigned lines)
{
    unsigned seen = 0;
    for (size_t i = 0; i < len; i++) {
        if (buf[i] == '\n' && ++seen >= lines) {
            return i + 1;
        }
    }
    return len;
}

/* Offset of the start of the last `lines` lines of buf (0 if there are fewer). */
static size_t last_lines_offset(const char *buf, size_t len, unsigned lines)
{
    unsigned seen = 0;
    for (size_t i = len; i > 0; i--) {
        if (buf[i - 1] == '\n' && ++seen > lines) {
            return i;
        }
    }
    return 0;
}

/* ----------------------------------------------------------------- handlers */

static esp_err_t h_index(httpd_req_t *req)
{
    httpd_resp_set_type(req, "text/html; charset=utf-8");
    httpd_resp_set_hdr(req, "Cache-Control", "no-store");
    return httpd_resp_send(req, (const char *)index_html_start,
                           (ssize_t)(index_html_end - index_html_start));
}

static esp_err_t send_json_error(httpd_req_t *req, const char *msg)
{
    char body[128];
    snprintf(body, sizeof(body), "{\"error\":\"%s\",\"files\":[]}", msg);
    httpd_resp_set_type(req, "application/json");
    return httpd_resp_sendstr(req, body);
}

/* httpd_err_code_t has no 503, so the status line is set explicitly. */
static esp_err_t send_unavailable(httpd_req_t *req, const char *msg)
{
    httpd_resp_set_status(req, "503 Service Unavailable");
    httpd_resp_set_type(req, "text/plain; charset=utf-8");
    return httpd_resp_sendstr(req, msg);
}

static esp_err_t h_files(httpd_req_t *req)
{
    if (!logger_sd_mounted()) {
        return send_json_error(req, "TF card is not mounted");
    }

    httpd_resp_set_type(req, "application/json");
    httpd_resp_set_hdr(req, "Cache-Control", "no-store");

    if (!sd_fs_lock(SD_LOCK_TIMEOUT_MS)) {
        return send_json_error(req, "TF card busy");
    }

    DIR *dir = opendir(APP_LOG_MOUNT_POINT);
    if (!dir) {
        sd_fs_unlock();
        return send_json_error(req, "cannot list the TF card");
    }

    char out[224];
    int n = clamp_len(snprintf(out, sizeof(out),
                               "{\"mount\":\"%s\",\"logging\":%s,\"files\":[",
                               APP_LOG_MOUNT_POINT,
                               logger_is_logging() ? "true" : "false"),
                      sizeof(out));
    esp_err_t err = httpd_resp_send_chunk(req, out, n);

    bool first = true;
    struct dirent *e;
    while (err == ESP_OK && (e = readdir(dir)) != NULL) {
        if (e->d_name[0] == '.') {
            continue;
        }

        char path[96];
        if (!resolve_file(e->d_name, path, sizeof(path))) {
            continue;
        }

        struct stat st;
        if (stat(path, &st) != 0) {
            continue;
        }

        n = clamp_len(snprintf(out, sizeof(out), "%s{\"name\":\"%s\",\"size\":%lu}",
                               first ? "" : ",", e->d_name,
                               (unsigned long)st.st_size),
                      sizeof(out));
        if (n > 0) {
            err = httpd_resp_send_chunk(req, out, n);
        }
        first = false;
    }

    closedir(dir);
    sd_fs_unlock();

    if (err == ESP_OK) {
        err = httpd_resp_send_chunk(req, "]}", 2);
    }
    if (err == ESP_OK) {
        err = httpd_resp_send_chunk(req, NULL, 0);   /* terminate */
    }
    return err;
}

static esp_err_t h_download(httpd_req_t *req)
{
    char name[MAX_NAME_LEN + 1];
    if (!get_name_arg(req, name, sizeof(name)) || !name_is_safe(name)) {
        return httpd_resp_send_err(req, HTTPD_400_BAD_REQUEST, "missing or bad ?f=");
    }
    if (!logger_sd_mounted()) {
        return send_unavailable(req, "TF card is not mounted");
    }

    if (!sd_fs_lock(SD_LOCK_TIMEOUT_MS)) {
        return send_unavailable(req, "TF card busy");
    }

    char path[96];
    FILE *f = resolve_file(name, path, sizeof(path)) ? fopen(path, "r") : NULL;
    sd_fs_unlock();

    if (!f) {
        return httpd_resp_send_err(req, HTTPD_404_NOT_FOUND, "no such file");
    }

    char *buf = malloc(DOWNLOAD_CHUNK_BYTES);
    if (!buf) {
        sd_fs_lock(SD_LOCK_TIMEOUT_MS);
        fclose(f);
        sd_fs_unlock();
        return httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR, "out of memory");
    }

    httpd_resp_set_type(req, "application/octet-stream");
    char disp[128];
    snprintf(disp, sizeof(disp), "attachment; filename=\"%s\"", name);
    httpd_resp_set_hdr(req, "Content-Disposition", disp);

    esp_err_t err = ESP_OK;
    for (;;) {
        size_t got;

        if (!sd_fs_lock(SD_LOCK_TIMEOUT_MS)) {
            err = ESP_FAIL;
            break;
        }
        got = fread(buf, 1, DOWNLOAD_CHUNK_BYTES, f);
        sd_fs_unlock();

        if (got == 0) {
            break;
        }
        /* Unlocked on purpose: a slow client must not stall the logger. */
        err = httpd_resp_send_chunk(req, buf, got);
        if (err != ESP_OK) {
            break;
        }
    }

    free(buf);
    sd_fs_lock(SD_LOCK_TIMEOUT_MS);
    fclose(f);
    sd_fs_unlock();

    if (err == ESP_OK) {
        err = httpd_resp_send_chunk(req, NULL, 0);
    }
    return err;
}

static esp_err_t h_preview(httpd_req_t *req)
{
    char name[MAX_NAME_LEN + 1];
    if (!get_name_arg(req, name, sizeof(name)) || !name_is_safe(name)) {
        return httpd_resp_send_err(req, HTTPD_400_BAD_REQUEST, "missing or bad ?f=");
    }
    if (!logger_sd_mounted()) {
        return send_unavailable(req, "TF card is not mounted");
    }

    /* tail=1 returns the newest lines, which is what a live log needs. */
    bool tail = false;
    char query[160];
    char val[8];
    if (httpd_req_get_url_query_len(req) > 0 &&
        httpd_req_get_url_query_str(req, query, sizeof(query)) == ESP_OK &&
        httpd_query_key_value(query, "tail", val, sizeof(val)) == ESP_OK) {
        tail = (val[0] == '1');
    }

    const unsigned lines = APP_WEB_PREVIEW_LINES;

    if (!sd_fs_lock(SD_LOCK_TIMEOUT_MS)) {
        return send_unavailable(req, "TF card busy");
    }

    char path[96];
    FILE *f = resolve_file(name, path, sizeof(path)) ? fopen(path, "r") : NULL;
    if (!f) {
        sd_fs_unlock();
        return httpd_resp_send_err(req, HTTPD_404_NOT_FOUND, "no such file");
    }

    long fsize = 0;
    if (fseek(f, 0, SEEK_END) == 0) {
        fsize = ftell(f);
    }
    if (fsize < 0) {
        fsize = 0;
    }

    size_t want = (size_t)fsize;
    if (want > PREVIEW_MAX_BYTES) {
        want = PREVIEW_MAX_BYTES;
    }

    char *buf = malloc(want + 1);
    if (!buf) {
        fclose(f);
        sd_fs_unlock();
        return httpd_resp_send_err(req, HTTPD_500_INTERNAL_SERVER_ERROR, "out of memory");
    }

    fseek(f, tail ? (fsize - (long)want) : 0, SEEK_SET);
    size_t got = fread(buf, 1, want, f);
    fclose(f);
    sd_fs_unlock();

    size_t body_len;
    if (tail) {
        const size_t off = last_lines_offset(buf, got, lines);
        if (off > 0) {
            memmove(buf, buf + off, got - off);
            body_len = got - off;
        } else {
            body_len = got;
        }
    } else {
        body_len = first_lines_len(buf, got, lines);
    }
    buf[body_len] = '\0';

    char hdr[48];
    snprintf(hdr, sizeof(hdr), "%s %u lines", tail ? "last" : "first", lines);

    httpd_resp_set_type(req, "text/plain; charset=utf-8");
    httpd_resp_set_hdr(req, "X-Preview", hdr);
    httpd_resp_set_hdr(req, "Cache-Control", "no-store");

    const esp_err_t err = httpd_resp_send(req, buf, (ssize_t)body_len);
    free(buf);
    return err;
}

/* --------------------------------------------------------------------- API */

esp_err_t web_server_start(void)
{
    httpd_config_t cfg = HTTPD_DEFAULT_CONFIG();
    cfg.server_port = APP_WEB_PORT;
    cfg.stack_size = 8192;      /* handlers build strings on the stack */
    cfg.max_uri_handlers = 8;
    cfg.lru_purge_enable = true;

    static const httpd_uri_t routes[] = {
        { .uri = "/",         .method = HTTP_GET, .handler = h_index,    .user_ctx = NULL },
        { .uri = "/files",    .method = HTTP_GET, .handler = h_files,    .user_ctx = NULL },
        { .uri = "/download", .method = HTTP_GET, .handler = h_download, .user_ctx = NULL },
        { .uri = "/preview",  .method = HTTP_GET, .handler = h_preview,  .user_ctx = NULL },
    };

    httpd_handle_t server = NULL;
    const esp_err_t err = httpd_start(&server, &cfg);
    if (err != ESP_OK) {
        ESP_LOGE(TAG, "httpd_start failed: %s", esp_err_to_name(err));
        return err;
    }

    for (size_t i = 0; i < sizeof(routes) / sizeof(routes[0]); i++) {
        if (httpd_register_uri_handler(server, &routes[i]) != ESP_OK) {
            ESP_LOGE(TAG, "failed to register %s", routes[i].uri);
        }
    }

    ESP_LOGI(TAG, "file browser on port %d (/ , /files , /download , /preview)",
             (int)APP_WEB_PORT);
    return ESP_OK;
}
